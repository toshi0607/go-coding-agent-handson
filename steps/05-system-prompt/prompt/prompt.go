// Package prompt はシステムプロンプトを組み立てる。
//
// システムプロンプトはエージェントの「役割定義書」で、3層で構成する:
//  1. 役割と行動方針(固定): エージェントとしての振る舞い方
//  2. 環境情報(起動時に注入): 作業ディレクトリ、OS、日付など。
//     LLMは実行環境を知らないので、教えなければ「あなたの環境によります」
//     のような答えしか返せない
//  3. プロジェクトメモリ(CLAUDE.md): プロジェクト固有の約束事。
//     ユーザーが毎回説明しなくても、エージェントが従うべき規約を
//     ファイルとしてリポジトリに置いておける
package prompt

import (
	"strings"
)

// MemoryFileName はプロジェクトメモリのファイル名。
const MemoryFileName = "CLAUDE.md"

const basePrompt = `あなたはターミナルで動くコーディングエージェントです。
ユーザーの依頼に対し、必要ならツールを使ってファイルの調査・編集・コマンド実行を行い、結果を簡潔に報告してください。

行動方針:
- 推測でファイルの内容を語らない。必ず read_file で実物を確認してから答える
- ファイルを編集する前に、対象ファイルを読んで現状を把握する
- コードを変更したら、可能ならビルドやテストで動作を確認する
- 回答は簡潔に。長い前置きや、聞かれていないことの説明はしない`

// Options は Build に渡す情報。
type Options struct {
	// WorkDir は作業ディレクトリ(CLAUDE.md の探索場所)。
	WorkDir string
}

// Build はシステムプロンプトを組み立てる。
func Build(opts Options) string {
	var b strings.Builder
	b.WriteString(basePrompt)

	// TODO(step05-1): 環境情報を追記する。
	//
	// LLMは実行環境を何も知らない。作業ディレクトリ(opts.WorkDir)、
	// OS(runtime.GOOS)、今日の日付(time.Now())あたりを教えて
	// おかないと、「あなたの環境によります」のような答えしか返せないし、
	// ツールに渡すパスの推測も外れやすくなる。
	//
	// 日付のフォーマットは time.Time.Format を使う(Goでは
	// "2006-01-02" というレイアウト文字列で書式を指定する)。

	// TODO(step05-2): プロジェクトメモリ(CLAUDE.md)を注入する。
	//
	// opts.WorkDir 直下の CLAUDE.md(MemoryFileName 定数)を読み、
	// 存在して中身があれば「プロジェクトメモリ」として全文を追記する。
	// このとき、これが何のセクションで、どう扱うべきものかの説明も
	// 添えること(ただのテキスト片を貼るだけでは、LLMはそれが
	// 「従うべき規約」だと分からない)。
	//
	// ファイルが無い・読めない場合は何も足さない。存在しない
	// セクションの見出しだけ残すような形でプロンプトを汚さないこと。
	//
	// 必要な import(fmt, os, path/filepath, runtime, time)は自分で足すこと。

	return b.String()
}
